"""Boundary recalibration, seed ensembles and conformal sets from saved probabilities (stage G: design, stage H: confirmation).

Design (seeds 0-2, stage G) picks the recalibration method by the rule in docs/V3_PLAN.md addendum 1; the confirmation
(seeds 10-14, stage H) tests H7, H8, H9 with that method. Writes docs/RECAL.md and results/tables/recal_*.csv.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from sensewhere import analysis, conformal, recal  # noqa: E402

R, T = ROOT / "results", ROOT / "results" / "tables"
T.mkdir(parents=True, exist_ok=True)
N_BOOT = 1000


def md(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("" if pd.isna(v) else (f"{v:.3f}" if isinstance(v, float) else str(v)) for v in r.values) + " |")
    return "\n".join(out)


def fmt(m, key="mean", lo="lo", hi="hi"):
    return f"{m[key]:+.3f} [{m[lo]:+.3f}, {m[hi]:+.3f}]" if key == "diff" else f"{m[key]:.3f} [{m[lo]:.3f}, {m[hi]:.3f}]"


def load(stage):
    f = R / f"stage{stage}" / f"stage{stage}_probs.npz"
    if not f.exists():
        return None
    z = np.load(f, allow_pickle=True)
    return {k: z[k] for k in z.files}


def window_labels(P_labels, inv):
    return P_labels[inv]


def arms_for(Z, seeds, methods):
    """preds[site][arm] -> (n_seeds, n_windows) window-level labels (track decisions broadcast); arms: <method> single, ensemble + <method>."""
    sites = sorted({k.split("|")[1] for k in Z if k.startswith("lp_te|")})
    y = {s: Z[f"y|{s}"] for s in sites}
    subj = {s: Z[f"subject|{s}"] for s in sites}
    preds = {s: {} for s in sites}
    for s in sites:
        trk = Z[f"track|{s}"]
        lps = [Z[f"lp_te|{s}|{sd}"].astype(np.float64) for sd in seeds]
        ens = recal.ensemble_logp(lps)
        for name, fn in methods.items():
            singles = []
            for lp in lps:
                P, inv = recal.track_mean_probs(lp, trk)
                singles.append(fn(P)[inv])
            preds[s][f"{name} | single model"] = np.stack(singles)
            P, inv = recal.track_mean_probs(ens, trk)
            preds[s][f"{name} | {len(seeds)}-seed ensemble"] = np.stack([fn(P)[inv]] * len(seeds))
    return y, subj, preds


def conformal_table(Z, seeds, alpha=0.1):
    rows = []
    sites = sorted({k.split("|")[1] for k in Z if k.startswith("lp_te|")})
    for s in sites:
        for sd in seeds:
            Pv, inv_v = recal.track_mean_probs(Z[f"lp_va|{s}|{sd}"].astype(np.float64), Z[f"track_va|{s}|{sd}"])
            yv = np.array([Z[f"y_va|{s}|{sd}"][inv_v == k][0] for k in range(len(Pv))])
            q = conformal.calibrate(Pv, yv, alpha)
            Pt, inv_t = recal.track_mean_probs(Z[f"lp_te|{s}|{sd}"].astype(np.float64), Z[f"track|{s}"])
            yt = np.array([Z[f"y|{s}"][inv_t == k][0] for k in range(len(Pt))])
            rows.append({"site": s, "seed": sd, **conformal.evaluate_sets(conformal.prediction_sets(Pt, q), yt)})
    d = pd.DataFrame(rows)
    return d.groupby("site")[["coverage", "mean_set_size", "singleton_share", "singleton_accuracy"]].mean().round(3).reset_index()


lines = ["# Boundary recalibration, ensembles and conformal sets", "", "Generated by `scripts/analyze_recal.py`. Hypotheses and the selection rule were fixed in `docs/V3_PLAN.md` (addendum 1) before this analysis.", ""]
G, H = load("G"), load("H")
selected = None
if G is not None:
    seeds = sorted({int(k.split("|")[2]) for k in G if k.startswith("lp_te|")})
    y, subj, preds = arms_for(G, seeds, recal.METHODS)
    res = analysis.multi_site_bootstrap(y, subj, preds, 3, reference="none | single model", n_boot=N_BOOT)
    rows = []
    for k, v in sorted(res.items()):
        rows.append({"arm": k, "track-vote balanced accuracy [95% CI]": fmt(v), "diff vs no recalibration, single model [95% CI]": "reference" if k == "none | single model" else fmt(v, "diff", "diff_lo", "diff_hi")})
    df = pd.DataFrame(rows)
    df.to_csv(T / "recal_design.csv", index=False)
    lines += [f"## Design on exploratory seeds {seeds} (stage G); exploratory, not a result", "", md(df), ""]
    per = analysis.per_site_scores(y, {s_: {k: v for k, v in preds[s_].items() if k.endswith("single model")} for s_ in preds}, 3)
    ps = pd.DataFrame([{"arm": k.replace(" | single model", ""), **{f"site {s_}": v[s_] for s_ in sorted(v)}} for k, v in sorted(per.items())])
    lines += ["### Per-site balanced accuracy, single models (the median and mean rules assume the two foot classes are about equally common at a site; check where they do not hold)", "", md(ps), ""]
    singles = {k.split(" | ")[0]: v["mean"] for k, v in res.items() if k.endswith("single model")}
    best = max((m for m in singles if m != "none"), key=lambda m: singles[m])
    selected = best if singles[best] > singles["none"] else None
    lines += [f"Rule: the recalibration with the highest mean single-model balanced accuracy is carried to confirmation only if it beats no recalibration. Best: `{best}` ({singles[best]:.3f} against {singles['none']:.3f} without). Carried forward: `{selected}`.", ""]
    (T / "recal_selected.json").write_text(json.dumps({"selected": selected}), encoding="utf-8")
    lines += ["### Conformal sets, nominal coverage 0.90 (calibrated on source validation tracks), single models, exploratory seeds", "", md(conformal_table(G, seeds)), ""]
if H is not None and selected is not None:
    seeds = sorted({int(k.split("|")[2]) for k in H if k.startswith("lp_te|")})
    methods = {"none": recal.METHODS["none"], selected: recal.METHODS[selected]}
    y, subj, preds = arms_for(H, seeds, methods)
    ref = "none | single model"
    tests = [
        (f"H7 {selected} recalibration beats plain base (single models)", f"{selected} | single model", ref),
        (f"H8 {len(seeds)}-seed ensemble beats the mean single model", f"none | {len(seeds)}-seed ensemble", ref),
        (f"H9 ensemble + {selected} beats the mean single model", f"{selected} | {len(seeds)}-seed ensemble", ref),
    ]
    out = []
    for name, a, b in tests:
        sub = {s: {a: preds[s][a], b: preds[s][b]} for s in preds}
        r95 = analysis.multi_site_bootstrap(y, subj, sub, 3, reference=b, n_boot=N_BOOT, ci=95.0)
        rbf = analysis.multi_site_bootstrap(y, subj, sub, 3, reference=b, n_boot=N_BOOT, ci=100 * (1 - 0.05 / 3))
        out.append({"hypothesis": name, "A [95% CI]": fmt(r95[a]), "B [95% CI]": fmt(r95[b]), "A - B [95% CI]": fmt(r95[a], "diff", "diff_lo", "diff_hi"),
                    "A - B [Bonferroni 98.3% CI]": fmt(rbf[a], "diff", "diff_lo", "diff_hi"), "confirmed (95% interval entirely above zero)": "yes" if r95[a]["diff_lo"] > 0 else "no"})
    df = pd.DataFrame(out)
    df.to_csv(T / "recal_confirmation.csv", index=False)
    lines += [f"## Confirmation on fresh seeds {seeds} (stage H)", "", md(df), ""]
    lines += ["### Conformal sets on the confirmatory seeds (nominal coverage 0.90)", "", md(conformal_table(H, seeds)), ""]
elif H is not None:
    lines += ["## Confirmation (stage H)", "", "No recalibration method beat no recalibration on the design seeds, so none was carried to confirmation (as pre-specified).", ""]

# ---- stage I: H5 (pretraining) and H6 (track-level GRU) against the stage H base models on the same seeds and splits
I = load("I")
if I is not None and H is not None:
    seeds = sorted({int(k.split("|")[2]) for k in I if k.startswith("lp_te|")})
    sites = sorted({k.split("|")[1] for k in I if k.startswith("lp_te|")})
    y = {s: H[f"y|{s}"] for s in sites}
    subj = {s: H[f"subject|{s}"] for s in sites}
    preds = {s: {} for s in sites}
    for s in sites:
        trk = H[f"track|{s}"]
        assert (I[f"track|{s}"] == trk).all()
        base, con, mil = [], [], []
        for sd in seeds:
            P, inv = recal.track_mean_probs(H[f"lp_te|{s}|{sd}"].astype(np.float64), trk)
            base.append(recal.METHODS["none"](P)[inv])
            P, inv = recal.track_mean_probs(I[f"lp_te|{s}|{sd}"].astype(np.float64), trk)
            con.append(recal.METHODS["none"](P)[inv])
            mil.append(I[f"mil_gru_long|{s}|{sd}"].astype(int))
        preds[s] = {"base": np.stack(base), "con_src_long_ft": np.stack(con), "mil_gru_long": np.stack(mil)}
    out = []
    for name, a in (("H5 source-only contrastive pretraining beats base", "con_src_long_ft"), ("H6 track-level GRU beats base", "mil_gru_long")):
        sub = {s: {a: preds[s][a], "base": preds[s]["base"]} for s in preds}
        r95 = analysis.multi_site_bootstrap(y, subj, sub, 3, reference="base", n_boot=N_BOOT, ci=95.0)
        rbf = analysis.multi_site_bootstrap(y, subj, sub, 3, reference="base", n_boot=N_BOOT, ci=100 * (1 - 0.05 / 5))
        out.append({"hypothesis": name, "A [95% CI]": fmt(r95[a]), "B [95% CI]": fmt(r95["base"]), "A - B [95% CI]": fmt(r95[a], "diff", "diff_lo", "diff_hi"),
                    "A - B [Bonferroni 99% CI]": fmt(rbf[a], "diff", "diff_lo", "diff_hi"), "confirmed (95% interval entirely above zero)": "yes" if r95[a]["diff_lo"] > 0 else "no"})
    df = pd.DataFrame(out)
    df.to_csv(T / "recal_confirmation_I.csv", index=False)
    lines += [f"## Confirmation of the stage F candidates on fresh seeds {seeds} (stage I; family of five tests, so 99% Bonferroni intervals)", "", md(df), ""]
(ROOT / "docs" / "RECAL.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote docs/RECAL.md")
