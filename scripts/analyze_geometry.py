"""Viewing-geometry diagnostic: does approach angle / speed / range differ by site, and do the v2 plain model's errors follow them?

Inputs: results/diag_geom/track_geometry.csv (from kaggle/diag_geom) and results/stageA predictions.
Writes results/tables/geometry_*.csv and docs/GEOMETRY.md. Every number in that file comes from this script.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import GroupKFold

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "results" / "tables"
T.mkdir(parents=True, exist_ok=True)
g = pd.read_csv(ROOT / "results/diag_geom/track_geometry.csv")
g["file_name"] = g.file_name.astype(np.int64)


def md(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("" if pd.isna(v) else (f"{v:.3f}" if isinstance(v, float) else str(v)) for v in r.values) + " |")
    return "\n".join(out)


lines = ["# Viewing-geometry diagnostic", "", "Generated by `scripts/analyze_geometry.py` from the tracker output in the DopplerWild release (position and velocity per window, aggregated per track). `lat_frac` is the share of the velocity that is across the radar's line of sight (0 = straight toward or away, 1 = fully across).", ""]
site_tab = g.groupby("location")[["speed", "lat_frac", "dist"]].agg(["mean", "std"]).round(2)
site_tab.columns = ["_".join(c) for c in site_tab.columns]
site_tab = site_tab.reset_index()
site_tab.to_csv(T / "geometry_by_site.csv", index=False)
lines += ["## Geometry by site (all labeled tracks)", "", md(site_tab), ""]

m = g[g.activity_load.notna()]
cls = m.groupby(["location", "activity_load"])[["speed", "lat_frac"]].mean().round(2).reset_index()
cls.to_csv(T / "geometry_by_site_class.csv", index=False)
lines += ["## Mean speed (m/s) and cross-beam share by site and class", "", md(cls), ""]

X = g[["speed", "lat_frac", "rad_frac", "dist", "x", "y"]].fillna(0).to_numpy()
site = g.location.to_numpy()
sites = sorted(set(site))
ps = np.zeros((len(g), len(sites)))
for tr, te in GroupKFold(5).split(X, site, g.global_id):
    c = HistGradientBoostingClassifier(max_iter=100, random_state=0).fit(X[tr], site[tr])
    for j, k in enumerate(c.classes_):
        ps[te, sites.index(k)] = c.predict_proba(X[te])[:, j]
auc = pd.DataFrame([{"site": s, "AUC from geometry alone": roc_auc_score((site == s).astype(int), ps[:, i])} for i, s in enumerate(sites)])
auc.to_csv(T / "geometry_site_auc.csv", index=False)
lines += ["## Can geometry alone tell the site? (subject-grouped 5-fold, one-vs-rest AUC; the spectrogram-based AUCs are in RESULTS.md section 1)", "", md(auc), ""]

z = np.load(ROOT / "results/stageA/stageA_preds.npz", allow_pickle=True)
rows = []
for k in z.files:
    if k.startswith("v2|") and "|erm|none|window|" in k:
        site_k, seed = k.split("|")[1], k.split("|")[-1]
        y, p, tr = z[f"y|{site_k}"], z[k], z[f"track|{site_k}"]
        d = pd.DataFrame({"track": tr, "y": y, "ok": p == y})
        a = d.groupby("track").agg(y=("y", "first"), acc=("ok", "mean")).reset_index()
        a["seed"] = seed
        rows.append(a)
a = pd.concat(rows)
a["file_name"] = a.track.str.split("|").str[0].astype(np.int64)
a["global_id"] = a.track.str.split("|").str[1].astype(int)
j = a.merge(g[["file_name", "global_id", "speed", "lat_frac", "dist"]], on=["file_name", "global_id"], how="left")
names = ["walking", "dual-hand load", "on wheels"]
j["class"] = j.y.map(dict(enumerate(names)))
for col, label in (("lat_frac", "cross-beam share quartile"), ("speed", "speed quartile"), ("dist", "range quartile")):
    j["bin"] = pd.qcut(j[col], 4, labels=["q1 (lowest)", "q2", "q3", "q4 (highest)"], duplicates="drop")
    t = j.groupby(["class", "bin"], observed=True).acc.mean().unstack().round(3).reset_index()
    t.to_csv(T / f"geometry_error_by_{col}.csv", index=False)
    lines += [f"## Window accuracy of the plain model by {label} (per-track accuracy, mean over tracks, sites and seeds)", "", md(t), ""]

# speed shortcut: does the speed ordering of walking vs dual-hand load flip at a site, and does recall follow?
sp = m[m.activity_load.isin(["normal_walking", "Dual-hand Load"])].groupby(["location", "activity_load"]).speed.mean().unstack()
rec = []
for site_k in sorted(sp.index):
    r = {}
    for c_i, c_n in ((0, "walking recall"), (1, "dual-hand recall")):
        vals = []
        for k in z.files:
            if k.startswith("v2|") and k.startswith(f"v2|{site_k}|erm|none|window|"):
                yy, pp_ = z[f"y|{site_k}"], z[k]
                vals.append(np.mean(pp_[yy == c_i] == c_i))
        r[c_n] = float(np.mean(vals))
    rec.append({"site": site_k, "walking speed (m/s)": sp.loc[site_k, "normal_walking"], "dual-hand speed (m/s)": sp.loc[site_k, "Dual-hand Load"],
                "walking minus dual-hand": sp.loc[site_k, "normal_walking"] - sp.loc[site_k, "Dual-hand Load"], **r})
shortcut = pd.DataFrame(rec)
shortcut.to_csv(T / "geometry_speed_shortcut.csv", index=False)
lines += ["## Speed shortcut: where walkers are not faster than carriers, walking recall collapses", "", md(shortcut), ""]
(ROOT / "docs" / "GEOMETRY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote docs/GEOMETRY.md")
